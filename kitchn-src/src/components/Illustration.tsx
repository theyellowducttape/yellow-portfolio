interface Props {
  name: string
  drawing?: string
  /** Position among the drawings in this step, to stagger them. */
  order: number
}

export function Illustration({ name, drawing, order }: Props) {
  const paths = DRAWINGS[drawing ?? ''] ?? DRAWINGS.bowl
  return (
    <svg className="illo" viewBox="0 0 64 64" role="img" aria-label={name}>
      {paths.map((d, i) => (
        <path key={i} d={d} pathLength={1} style={{ '--i': order * 3 + i } as CSSProperties} />
      ))}
    </svg>
  )
}
